-- PostgreSQL equivalent of existing schema 7. No sample data or credentials.
CREATE TABLE students (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                contact TEXT NOT NULL DEFAULT '',
                source TEXT NOT NULL DEFAULT '',
                level TEXT NOT NULL DEFAULT '',
                pain_points TEXT NOT NULL DEFAULT '',
                goals TEXT NOT NULL DEFAULT '',
                remarks TEXT NOT NULL DEFAULT ''
            , joined_at TEXT, starred BIGINT NOT NULL DEFAULT 0, revision BIGINT NOT NULL DEFAULT 0);

CREATE TABLE lessons (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                student_id BIGINT NOT NULL,
                kind TEXT NOT NULL
                    CHECK (kind IN ('私教', '陪打')),
                starts_at TEXT NOT NULL,
                ends_at TEXT NOT NULL,
                location TEXT NOT NULL,
                status TEXT NOT NULL DEFAULT '待上课',
                reason TEXT NOT NULL DEFAULT '',
                notified_at TEXT,
                absence BIGINT NOT NULL DEFAULT 0,
                charge_due BIGINT NOT NULL DEFAULT 0,
                charged BIGINT NOT NULL DEFAULT 0,
                package_id BIGINT,
                note TEXT NOT NULL DEFAULT '',
                next_goal TEXT NOT NULL DEFAULT '', checkin_done BIGINT NOT NULL DEFAULT 0, checked_in_at TEXT, cancellation_24h BIGINT, original_lesson_id BIGINT , reschedule_pending BIGINT NOT NULL DEFAULT 0, change_reason TEXT NOT NULL DEFAULT '', proposed_start TEXT, proposed_end TEXT, proposed_location TEXT, coach_id BIGINT , revision BIGINT NOT NULL DEFAULT 0, archived BIGINT NOT NULL DEFAULT 0 CHECK(archived IN (0,1)), booking_slot_id BIGINT , attendance_confirmed BIGINT NOT NULL DEFAULT 0 CHECK(attendance_confirmed IN (0,1))
            );

CREATE TABLE daily_notes(day TEXT PRIMARY KEY,body TEXT NOT NULL DEFAULT '',updated_at TEXT NOT NULL);

CREATE TABLE ops_migrations(version BIGINT PRIMARY KEY, applied_at BIGINT NOT NULL);

CREATE TABLE coaches(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL);

CREATE TABLE accounts(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT NOT NULL UNIQUE,
 display_name TEXT NOT NULL, password_hash TEXT NOT NULL,
 role TEXT NOT NULL CHECK(role IN ('coach','operator','system_admin')),
 coach_id BIGINT UNIQUE ,
 active BIGINT NOT NULL DEFAULT 1 CHECK(active IN (0,1)),
 created_at BIGINT NOT NULL,
 CHECK(role='system_admin' OR coach_id IS NOT NULL)
);

CREATE TABLE auth_sessions(
