CREATE TABLE "packages" (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                student_id BIGINT NOT NULL,
                kind TEXT NOT NULL
                    CHECK (kind IN ('私教', '陪打')),
