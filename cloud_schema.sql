CREATE TABLE feedback_submissions(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lesson_id BIGINT NOT NULL ,
 coach_id BIGINT NOT NULL ,
 feedback_revision BIGINT NOT NULL,
 note TEXT NOT NULL,next_goal TEXT NOT NULL,
 submitted_by BIGINT ,submitted_at TEXT NOT NULL,
 state TEXT NOT NULL CHECK(state IN ('pending','approved','returned','withdrawn')),
 is_current BIGINT NOT NULL DEFAULT 1 CHECK(is_current IN (0,1)),
 reviewed_by BIGINT ,reviewed_at TEXT,review_comment TEXT NOT NULL DEFAULT '',
 source TEXT NOT NULL DEFAULT 'submission' CHECK(source IN ('submission','migration')),
 UNIQUE(lesson_id,feedback_revision)
);

CREATE TABLE feedback_reads(
 submission_id BIGINT NOT NULL ,
 account_id BIGINT NOT NULL ,opened_at TEXT NOT NULL,
 PRIMARY KEY(submission_id,account_id)
);

CREATE TABLE credit_ledger(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id BIGINT NOT NULL ,
 coach_id BIGINT NOT NULL ,
 kind TEXT NOT NULL CHECK(kind IN ('私教','陪打')),
 package_id BIGINT NOT NULL ,
 lesson_id BIGINT ,
 action TEXT NOT NULL CHECK(action IN ('opening','purchase','void_purchase','lesson','absence','return')),
 delta BIGINT NOT NULL,
 actor_id BIGINT ,
 reason TEXT NOT NULL DEFAULT '',
 created_at TEXT NOT NULL, active BIGINT NOT NULL DEFAULT 1 CHECK(active IN (0,1)), reverses_id BIGINT ,
 CHECK((action IN ('lesson','absence') AND delta=-1 AND lesson_id IS NOT NULL)
 OR (action='return' AND delta=1 AND lesson_id IS NOT NULL)
 OR (action='purchase' AND delta>0 AND lesson_id IS NULL)
 OR (action='opening' AND delta>=0 AND lesson_id IS NULL)
 OR (action='void_purchase' AND delta<0 AND lesson_id IS NULL))
);

CREATE TABLE credit_requests(
